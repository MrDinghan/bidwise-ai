package com.bidwise.listing;

import com.bidwise.user.User;
import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OrderColumn;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

/**
 * An auction listing created by a seller. Mirrors the {@code listings} table.
 *
 * <p>State changes go through guarded domain methods ({@link #publish()},
 * {@link #cancel()}, {@link #applyEdits}) rather than setters, so invariants live
 * in one place. Getters are generated by Lombok.
 */
@Entity
@Table(name = "listings")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED) // required by JPA
public class Listing {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "seller_id", nullable = false)
    private User seller;

    @Column(nullable = false, length = 140)
    private String title;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private Category category;

    @Column(nullable = false, length = 4000)
    private String description;

    @Enumerated(EnumType.STRING)
    @Column(name = "item_condition", nullable = false, length = 20)
    private ItemCondition condition;

    @ElementCollection
    @CollectionTable(name = "listing_photos", joinColumns = @JoinColumn(name = "listing_id"))
    @OrderColumn(name = "position")
    @Column(name = "url", nullable = false, length = 1000)
    private List<String> photos = new ArrayList<>();

    @Column(name = "start_price", nullable = false, precision = 12, scale = 2)
    private BigDecimal startPrice;

    @Column(name = "bid_increment", nullable = false, precision = 12, scale = 2)
    private BigDecimal bidIncrement;

    @Column(name = "current_price", nullable = false, precision = 12, scale = 2)
    private BigDecimal currentPrice;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private ListingStatus status;

    @Column(name = "start_at")
    private Instant startAt;

    @Column(name = "end_at")
    private Instant endAt;

    @Column(name = "pickup_location", length = 255)
    private String pickupLocation;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /**
     * Creates a new listing in {@link ListingStatus#DRAFT}. The current price starts
     * at the start price; the auction window opens only on {@link #publish()}.
     */
    public Listing(
            User seller,
            String title,
            Category category,
            String description,
            ItemCondition condition,
            List<String> photos,
            BigDecimal startPrice,
            BigDecimal bidIncrement,
            String pickupLocation,
            Instant endAt) {
        this.seller = seller;
        this.title = title;
        this.category = category;
        this.description = description;
        this.condition = condition;
        this.photos = photos == null ? new ArrayList<>() : new ArrayList<>(photos);
        this.startPrice = startPrice;
        this.bidIncrement = bidIncrement;
        this.currentPrice = startPrice;
        this.pickupLocation = pickupLocation;
        this.endAt = endAt;
        this.status = ListingStatus.DRAFT;
        Instant now = Instant.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    /** True if the given user id is the owner of this listing. */
    public boolean isOwnedBy(Long userId) {
        return seller != null && seller.getId() != null && seller.getId().equals(userId);
    }

    /**
     * Edits the mutable presentation/pricing fields. Allowed only while the listing
     * is still {@code DRAFT} or {@code ACTIVE}.
     */
    public void applyEdits(
            String title,
            Category category,
            String description,
            ItemCondition condition,
            List<String> photos,
            BigDecimal startPrice,
            BigDecimal bidIncrement,
            String pickupLocation,
            Instant endAt) {
        if (status != ListingStatus.DRAFT && status != ListingStatus.ACTIVE) {
            throw new IllegalListingStateException(
                    "Listing can only be edited while it is a draft or active");
        }
        this.title = title;
        this.category = category;
        this.description = description;
        this.condition = condition;
        this.photos = photos == null ? new ArrayList<>() : new ArrayList<>(photos);
        this.startPrice = startPrice;
        this.bidIncrement = bidIncrement;
        // No bids exist in P1, so the current price tracks the start price.
        if (status == ListingStatus.DRAFT) {
            this.currentPrice = startPrice;
        }
        this.pickupLocation = pickupLocation;
        this.endAt = endAt;
        this.updatedAt = Instant.now();
    }

    /**
     * Publishes a draft: opens the auction window now and makes it searchable.
     * Requires a future {@code endAt}.
     */
    public void publish() {
        if (status != ListingStatus.DRAFT) {
            throw new IllegalListingStateException("Only a draft listing can be published");
        }
        Instant now = Instant.now();
        if (endAt == null || !endAt.isAfter(now)) {
            throw new IllegalListingStateException("Listing must have an end time in the future");
        }
        this.startAt = now;
        this.status = ListingStatus.ACTIVE;
        this.updatedAt = now;
    }

    /** Cancels an active listing (no winner). */
    public void cancel() {
        if (status != ListingStatus.ACTIVE) {
            throw new IllegalListingStateException("Only an active listing can be cancelled");
        }
        this.status = ListingStatus.CLOSED;
        this.updatedAt = Instant.now();
    }
}
